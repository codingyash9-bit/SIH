create or replace function public.set_observed_on()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.observed_on := (new.captured_at at time zone 'Asia/Kolkata')::date;
  return new;
end;
$$;

drop trigger if exists detections_set_observed_on on public.detections;
create trigger detections_set_observed_on
before insert or update of captured_at on public.detections
for each row execute function public.set_observed_on();

