-- Prototype Realtime: compact INSERT events only. At city scale, publish a reduced
-- event contract through Supabase Broadcast or the Python/Java realtime gateway.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'detections'
  ) then
    alter publication supabase_realtime add table public.detections;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'alerts'
  ) then
    alter publication supabase_realtime add table public.alerts;
  end if;
end $$;

