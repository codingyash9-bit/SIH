-- These views power the dashboard's Live Today and Recorded Days sections.
-- security_invoker makes the caller's RLS policies apply to underlying tables.
create or replace view public.live_today_detections
with (security_invoker = true)
as
select d.*
from public.detections d
where d.observed_on = (now() at time zone 'Asia/Kolkata')::date;

create or replace view public.historical_detections
with (security_invoker = true)
as
select d.*
from public.detections d
where d.observed_on < (now() at time zone 'Asia/Kolkata')::date;

create or replace view public.recorded_days
with (security_invoker = true)
as
select
  d.jurisdiction_id,
  d.observed_on,
  count(*)::bigint as detection_count,
  count(distinct d.camera_id)::bigint as active_camera_count,
  count(*) filter (where d.plate_token is not null)::bigint as readable_plate_count,
  count(*) filter (where d.is_watchlist_candidate)::bigint as watchlist_candidate_count,
  min(d.captured_at) as first_detection_at,
  max(d.captured_at) as last_detection_at
from public.detections d
group by d.jurisdiction_id, d.observed_on;

create or replace function public.current_operator_jurisdiction()
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select p.jurisdiction_id
  from public.operator_profiles p
  where p.user_id = (select auth.uid()) and p.active
$$;

revoke all on function public.current_operator_jurisdiction() from public;
grant execute on function public.current_operator_jurisdiction() to authenticated;

